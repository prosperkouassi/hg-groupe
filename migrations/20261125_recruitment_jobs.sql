-- All DATETIME values in this table are written in UTC.
CREATE TABLE recruitment_jobs (
  slug VARCHAR(140) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  city VARCHAR(120) NOT NULL,
  country VARCHAR(120) NOT NULL,
  country_code CHAR(2) NOT NULL,
  company VARCHAR(180) NULL,
  contract ENUM('Stage', 'Alternance', 'CDD', 'CDI', 'Freelance', 'Mission', 'Temporaire') NOT NULL,
  work_mode ENUM('Sur site', 'Hybride', 'Télétravail') NOT NULL,
  published_at DATETIME NULL,
  deadline DATETIME NULL,
  closed BOOLEAN NOT NULL DEFAULT FALSE,
  cover_letter_required BOOLEAN NOT NULL DEFAULT FALSE,
  positions SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  experience VARCHAR(180) NOT NULL,
  education VARCHAR(180) NOT NULL,
  salary VARCHAR(180) NULL,
  hours VARCHAR(180) NULL,
  start_date DATE NULL,
  description TEXT NOT NULL,
  missions JSON NOT NULL,
  profile JSON NOT NULL,
  skills JSON NOT NULL,
  benefits JSON NOT NULL,
  process JSON NOT NULL,
  recruiter JSON NULL,
  INDEX recruitment_jobs_publication (published_at, slug),
  CHECK (positions > 0),
  CHECK (slug <> 'confirmation')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
